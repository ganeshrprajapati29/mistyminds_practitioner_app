/// Every bundled asset path. Screens never spell a path out themselves.
///
/// `assets/images/` and `assets/brand/` are produced from the raw drops in
/// `assets/` by `tool/prepare_assets.dart` (cut-outs, trimmed and optimised
/// files). The brand icon SVGs are used exactly as supplied.
abstract final class AppAssets {
  static const String _img = 'assets/images';

  // ---- Brand ---------------------------------------------------------------
  static const String wordmark = '$_img/logo_wordmark.png';

  // ---- Illustrations -------------------------------------------------------
  static const String welcomeBackground = '$_img/welcome_bg.jpg';

  /// Smiling cloud with a heart — "Ready when you are."
  static const String cloudReady = '$_img/cloud_ready.png';

  /// Sleepy, content cloud — calm confirmations and session complete.
  static const String cloudCalm = '$_img/cloud_calm.png';

  /// Cloud in headphones on white — listening moments on white cards.
  static const String cloudListening = '$_img/cloud_listening.jpg';

  /// Concentric rings around a person — waiting for a request.
  static const String waitingRequest = '$_img/waiting_request.png';

  /// Faceless portrait for a client who chose to stay anonymous.
  static const String anonymousClient = '$_img/anonymous_client.png';

  // ---- Icons (supplied SVGs) -----------------------------------------------
  static const String iconAudio = 'assets/icon_audio.svg';
  static const String iconCalendar = 'assets/icon_calendar.svg';
  static const String iconChat = 'assets/icon_chat.svg';
  static const String iconClients = 'assets/icon_clients.svg';
  static const String iconClock = 'assets/icon_clock.svg';
  static const String iconHome = 'assets/icon_home.svg';
  static const String iconNotification = 'assets/icon_notification.svg';
  static const String iconProfile = 'assets/icon_profile.svg';
  static const String iconSessions = 'assets/icon_sessions.svg';
  static const String iconTalkNow = 'assets/icon_talk_now.svg';
  static const String iconVideo = 'assets/icon_video.svg';
  static const String iconWallet = 'assets/icon_wallet.svg';

  // ---- Bottom navigation ---------------------------------------------------
  //
  // Tile-free, pre-coloured versions of the brand icons, generated by
  // `tool/prepare_assets.dart`.
  static const String _nav = 'assets/icons/nav';
  static String navActive(String name) => '$_nav/${name}_active.svg';
  static String navInactive(String name) => '$_nav/${name}_inactive.svg';

  static const List<String> allIcons = <String>[
    iconAudio,
    iconCalendar,
    iconChat,
    iconClients,
    iconClock,
    iconHome,
    iconNotification,
    iconProfile,
    iconSessions,
    iconTalkNow,
    iconVideo,
    iconWallet,
  ];
}
